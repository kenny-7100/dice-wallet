export function translateMnemonic(mnemonic: string): string {
  return mnemonic
    .split(" ")
    .map((word) => {
      const translation = ENGLISH_TO_SIMPLIFIED_CHINESE[word];
      if (!translation) {
        throw new Error(`missing mnemonic translation for: ${word}`);
      }

      return translation;
    })
    .join(" ");
}

